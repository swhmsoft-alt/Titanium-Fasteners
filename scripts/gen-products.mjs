/* search-index.ts — 客户端筛选索引（②B）。
 *
 * 只含**筛选维度**，不含规格矩阵：族数 × 维度值，体积与族数线性而非与 SKU 数线性。
 * 矩阵留在族页静态渲染 —— 客户端不需要它。
 *
 * 每行的维度值取自该族的矩阵实际数据（threads / lengths 去重自 dimensions），
 * 所以筛选结果与族页表里的实际规格严格一致，不会出现「筛出来却没这个规格」。
 *
 * 维度值自带显示标签 —— 客户端不 import 数据层，也就不用把整包
 * MATERIALS/STANDARDS/FINISHES 打进 JS bundle。
 */
const stdLabel = new Map((dicts['standards.csv']?.rows ?? []).map((r) => [r.id, r.label]));
const matLabel = new Map((dicts['materials.csv']?.rows ?? []).map((r) => [r.id, r.name]));
const finLabel = new Map((dicts['finishes.csv']?.rows ?? []).map((r) => [r.id, r.name]));

const facet = (ids, labelMap) => ids.map((id) => ({ id, label: labelMap.get(id) ?? id }));

/* ── 路由常量（唯一形态）────────────────────────────────────────────────
 * 全站产品区统一到 /global-en/eshop/ 前缀：
 *   总览      /global-en/eshop/
 *   分类页    /global-en/eshop/c/<category_id>/
 *   产品族页  /global-en/eshop/p/<family_id>/
 * 仓库禁止跳转/重定向 —— 这个形态一旦生成就是契约。
 */
const ESHOP_ROUTE_BASE = '/global-en/eshop/';
const familyRoute = (id) => `${ESHOP_ROUTE_BASE}p/${id}/`;
const categoryRoute = (id) => `${ESHOP_ROUTE_BASE}c/${id}/`;

const searchIndex = {
	categories: catRows.map((c) => ({ id: c.id, name: c.name })),
	families: families.map((f) => {
		const rows = dimensions.get(f.family_id) ?? [];
		const threads = [...new Set(rows.map((r) => r.thread).filter(Boolean))].sort();
		const lengths = [
			...new Set(rows.map((r) => r.length).filter(Boolean).map(Number).filter(Number.isFinite)),
		].sort((a, b) => a - b);
		return {
			family_id: f.family_id,
			name: f.name,
			category: f.category ?? '',
			description: f.description ?? '',
			sku: familySkus.get(f.family_id) ?? '',
			image: familyAssets.get(f.family_id)?.image ?? '',
			url: familyRoute(f.family_id),
			standards: facet(split(f.standards), stdLabel),
			materials: facet(split(f.materials), matLabel),
			finishes: facet(split(f.finishes), finLabel),
			threads,
			lengths,
			size_count: rows.length,
			status: f.status === 'published' ? 'published' : 'draft',
		};
	}),
};

