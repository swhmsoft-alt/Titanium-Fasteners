const familyFilters = (f) => {
	const out = {};
	for (const d of DIMENSIONS_VIEW) out[d.id] = d.values(f);
	return out;
};

const productCard = (f) => ({
	sku: familySkus.get(f.family_id) ?? f.family_id,
	standards: split(f.standards).map((id) => stdLabel.get(id) ?? id),
	title: f.name,
	href: familyRoute(f.family_id),
	image: familyAssets.get(f.family_id)?.image ?? '',
	alt: f.name,
	description: f.description ?? '',
	material: [...split(f.materials).map((id) => matLabel.get(id) ?? id), ...split(f.finishes).map((id) => finLabel.get(id) ?? id)].join(' / '),
	status: f.status === 'published' ? 'published' : 'draft',
	filters: familyFilters(f),
});

/** 全部分类（分类导航滑轨用）—— 只列有族的分类，空分类不给死路入口。 */
const categoryCards = catRows
	.filter((c) => families.some((f) => f.category === c.id))
	.map((c) => ({
		title: c.name,
		products: families.filter((f) => f.category === c.id).length,
		href: categoryRoute(c.id),
		image: c.image ?? '',
		alt: c.name,
	}));

/** 左侧筛选栏的维度组 —— 取值来自全部族（不随当前筛选收窄，否则会自我收窄）。 */
const filterGroups = DIMENSIONS_VIEW.map((d) => {
	const map = new Map();
	for (const f of families) {
		for (const v of d.values(f)) if (!map.has(v)) map.set(v, d.names([v])[0]);
	}
	const ids = [...map.keys()];
	const numeric = ids.every((v) => Number.isFinite(Number(v)));
	ids.sort((a, b) => (numeric ? Number(a) - Number(b) : map.get(a).localeCompare(map.get(b))));
	return { id: d.id, label: d.label, options: ids.map((id) => ({ id, label: map.get(id) })) };
});

const categoryViews = catRows
	.filter((c) => families.some((f) => f.category === c.id))
	.map((c) => {
		const own = families.filter((f) => f.category === c.id);
		const pub = own.filter((f) => f.status === 'published');
		/* 有 published 就只列 published；一个都没有则全列并由页面输出 noindex。 */
		const shown = pub.length ? pub : own;
		return {
			id: c.id,
			heading: c.name,
			description: c.description ?? '',
			image: c.image ?? '',
			breadcrumb: [
				{ label: 'Home', href: '/' },
				{ label: 'Products', href: ESHOP_ROUTE_BASE },
				{ label: c.name, href: categoryRoute(c.id) },
			],
			productCount: shown.length,
			products: shown.map(productCard),
			hasPublished: pub.length > 0,
		};
	});

