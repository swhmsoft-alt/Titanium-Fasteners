/**
 * scripts/gen-target.mjs — probe JSON → acceptance target file.
 *
 * The target file is what scripts/measure-page.mjs compares the local build
 * against. Generating it from the probe removes the single most expensive
 * manual step of a recreation: transcribing measured numbers by hand (and,
 * worse, transcribing them twice).
 *
 * Usage:
 *   node scripts/gen-target.mjs qa/ref/eshop.json --out qa/targets/eshop.json
 *                                 [--page-type eshop] [--label "1 FasteningTech"]
 *
 * The block labels come from the section's own heading text, so they stay
 * meaningful without manual renaming.
 */
import { writeFileSync, mkdirSync, existsSync, readFileSync } from 'node:fs';
import { dirname } from 'node:path';

const args = process.argv.slice(2);
const probeFile = args.find((a) => !a.startsWith('--'));
if (!probeFile) {
	console.error('usage: node scripts/gen-target.mjs <probe.json> [--out f] [--page-type t]');
	process.exit(1);
}
const flag = (name, fallback) => {
	const i = args.indexOf(name);
	return i >= 0 ? args[i + 1] : fallback;
};
const OUT = flag('--out', probeFile.replace('qa/ref/', 'qa/targets/').replace(/\.json$/, '.json'));
/* Default page type = the probe file's own name, so a target file never has to
   be labelled by hand ("qa/ref/eshop.json" -> pageType "eshop"). */
const PAGE_TYPE = flag(
	'--page-type',
	probeFile.replace(/^.*[\\/]/, '').replace(/\.json$/i, ''),
);

const probe = JSON.parse(readFileSync(probeFile, 'utf8'));

/** Headings live in probe.texts; find the nearest one above a section. */
const headingFor = (sec) => {
	const candidates = probe.texts
		.filter((t) => /^H[1-4]$/.test(t.tag) && t.y <= sec.y + 4)
		.sort((a, b) => b.y - a.y);
	return candidates[0]?.text ?? null;
};

/**
 * Block label.
 *
 * The section's own heading is the label that actually identifies the block.
 * The "nearest heading above" fallback is only used when the section has no
 * heading of its own — with it, repeated labels ("1 Fastening Technology" ×5)
 * are unavoidable and the acceptance table becomes unreadable.
 */
const labelFor = (sec, i) => {
	const own = sec.headText?.trim();
	const label = own || headingFor(sec) || `block ${i + 1}`;
	return `${i + 1} ${label}`.slice(0, 40);
};

const sections = probe.sections.map((s, i) => ({
	block: labelFor(s, i),
	y: s.y,
	h: s.h,
	headSize: s.headSize,
}));

const target = {
	$comment:
		`AUTO-GENERATED by scripts/gen-target.mjs from ${probeFile}. ` +
		`Reference: ${probe.url} @ ${probe.viewport.width}x${probe.viewport.height}. ` +
		'Do not hand-edit — regenerate instead.',
	pageType: PAGE_TYPE,
	viewport: `${probe.viewport.width}x${probe.viewport.height}`,
	sections,
	notes: [
		`body height ${probe.bodyHeight}px, h-overflow ${probe.overflow.scrollWidth - probe.overflow.clientWidth}px`,
		`header ${probe.header ? `${probe.header.h}px ${probe.header.pos}` : 'n/a'}; footer ${probe.footer ? `${probe.footer.h}px` : 'n/a'}`,
		`probe collected ${probe.texts.length} text runs, ${probe.links.length} links, ${probe.figures.length} figures`,
	],
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, JSON.stringify(target, null, '\t'), 'utf8');

console.log(`target ${OUT}`);
for (const s of sections) {
	console.log(`  ${String(s.block).padEnd(20)} y=${String(s.y).padStart(5)} h=${String(s.h).padStart(5)}  ${s.headSize ?? ''}`);
}
